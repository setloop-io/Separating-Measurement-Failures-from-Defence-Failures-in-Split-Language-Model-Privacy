#!/usr/bin/env python3
"""Generate appendix_evidence.tex: the v14/v15 artifact ledger.

One row per committed runner JSON in paper-data/latent_v14/ and
paper-data/latent_v15/: cell, budget, held-out MI (bits), dual variable,
frozen-attacker upper-95 excess, utility delta, eval ratio, budget gate.
Every number is read from the artifact at build time — the table cannot
drift from the data.  Run from the repo root:
    python3 bin/make_evidence_appendix.py > papers/draft/appendix_evidence.tex
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(x, nd=3):
    return "---" if x is None else f"{x:+.{nd}f}"


def fmt_sci(x):
    if x is None:
        return "---"
    if abs(x) < 0.01:
        s = f"{x:.1e}"
        mantissa, exp = s.split("e")
        return f"${mantissa}\\times10^{{{int(exp)}}}$"
    return f"{x:+.4f}"


def rows_for(version):
    d = ROOT / "paper-data" / f"latent_{version}"
    for runner in sorted(d.glob("*.json")):
        if runner.name.endswith(("_attacker.json", "_matching.json",
                                 "_sensitivity.json", "_ceprobe.json")):
            continue
        r = json.loads(runner.read_text())
        cell = runner.stem.replace(f"latent_{version}_", "")
        att = runner.with_name(runner.stem + "_attacker.json")
        upper95 = "---"
        if att.exists():
            a = json.loads(att.read_text())
            upper95 = f"{a['summary'][0]['upper95_excess_over_majority_pp']:+.2f}"
        gate = r["gates"].get("mine_budget_satisfied")
        gate_s = {True: "pass", False: "FAIL", None: "---"}[gate]
        budget = r.get("mine_budget_bits")
        yield (cell.replace("_", r"\_"),
               "---" if budget is None else f"{budget}",
               fmt_sci(r.get("mine_mi_bits_held_out")),
               "---" if r.get("mine_lambda_final") is None
               else f"{r['mine_lambda_final']:.3f}",
               upper95, fmt(r.get("eval_loss_delta")),
               f"{r.get('eval_time_ratio', 0):.2f}$\\times$", gate_s)


def table(version, caption):
    rows = "\n".join(
        f"  {c} & {b} & {mi} & {lam} & {ex} & {ut} & {ra} & {g} \\\\"
        for c, b, mi, lam, ex, ut, ra, g in rows_for(version))
    return (
        "\\begin{table}[t]\n\\centering\\tiny\n"
        "\\setlength{\\tabcolsep}{3pt}\n"
        f"\\caption{{{caption}}}\n"
        f"\\label{{tab:ledger_{version}}}\n"
        "\\resizebox{\\columnwidth}{!}{%\n"
        "\\begin{tabular}{lccccccc}\n\\toprule\n"
        "cell & $B$ & MI (bits) & $\\lambda$ & excess u95 & util & ratio "
        "& gate \\\\\n\\midrule\n"
        f"{rows}\n\\bottomrule\n\\end{{tabular}}}}\n\\end{{table}}\n")


print("% AUTO-GENERATED by bin/make_evidence_appendix.py — do not edit.")
print(table("v14", "v14 evidence ledger: budget sweep, seeds, transfer, "
                  "integrity, and falsification cells.  Every value is read "
                  "from the committed artifact named by the row."))
print(table("v15", "v15 evidence ledger: estimator-power and "
                  "binding-range cells (strengthened estimator)."))
